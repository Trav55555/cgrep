"""Generates src/word.inc, the reference's -w word characters.

    python3 -I tools/word_table.py PERL_WORD_RS > src/word.inc
    python3 -I tools/word_table.py PERL_WORD_RS --check src/word.inc

PERL_WORD_RS is regex-syntax's src/unicode_tables/perl_word.rs, the \\w
table ripgrep's regex engine uses (every regex-syntax 0.8 release carries
the same Unicode 16.0.0 table). --check exits 1 unless the file given
equals what this script would write.
"""

import re
import sys


def ranges(source: str):
    header = re.search(r"Unicode version: ([0-9]+(?:\.[0-9]+)*)", source)
    body = source[source.index("PERL_WORD"):]
    pairs = []
    for a, b in re.findall(r"\('((?:\\u\{[0-9a-fA-F]+\}|\\.|[^'\\])+)', '((?:\\u\{[0-9a-fA-F]+\}|\\.|[^'\\])+)'\)", body):
        pairs.append((char(a), char(b)))
    return (header.group(1) if header else "unknown"), pairs


def char(text: str) -> int:
    if text.startswith("\\u{"):
        return int(text[3:-1], 16)
    if text.startswith("\\"):
        return ord({"n": "\n", "t": "\t", "r": "\r", "0": "\0"}.get(text[1], text[1]))
    assert len(text) == 1, text
    return ord(text)


def render(version: str, pairs) -> str:
    lines = [
        "/* -w word characters: the reference's \\w (regex-syntax PERL_WORD,",
        f" * Unicode {version}), as sorted inclusive code point ranges. Generated by",
        " * tools/word_table.py; do not edit. Included by cgrep.c. */",
        "static const unsigned long word_ranges[][2] = {",
    ]
    for a, b in pairs:
        lines.append(f"    {{0x{a:x}UL, 0x{b:x}UL}},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    with open(sys.argv[1], encoding="utf-8") as f:
        version, pairs = ranges(f.read())
    assert pairs and all(a <= b for a, b in pairs)
    assert all(pairs[i][1] < pairs[i + 1][0] for i in range(len(pairs) - 1))
    text = render(version, pairs)
    if len(sys.argv) == 4 and sys.argv[2] == "--check":
        with open(sys.argv[3], encoding="utf-8") as f:
            return 0 if f.read() == text else 1
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
